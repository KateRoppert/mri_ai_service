class PipelineRun(Base):
    """Модель запуска pipeline"""
    __tablename__ = "pipeline_runs"
    
    run_id = Column(String, primary_key=True, index=True)
    input_path = Column(String, nullable=False)
    output_path = Column(String, nullable=False)
    status = Column(String, nullable=False, default="pending")
    
    # Прогресс
    current_stage = Column(Integer, nullable=True)
    overall_progress = Column(Float, default=0.0)
    
    # Качество
    quality_score = Column(Float, nullable=True)
    quality_category = Column(String, nullable=True)
    
    # Временные метки
    created_at = Column(DateTime, default=datetime.utcnow)
    started_at = Column(DateTime, nullable=True)
    completed_at = Column(DateTime, nullable=True)
    
    # Ошибки
    error_message = Column(Text, nullable=True)
    
    # Путь к конфигу
    config_path = Column(String, nullable=True)

    # Тип поражения (glioblastoma / multiple_sclerosis)
    lesion_type = Column(String, nullable=True, default='glioblastoma')

    # The Kappa dataset this run numbers its subjects in and uploads to. Fixed
    # once at start (backend/numbering.py) so numbering and upload cannot
    # target different datasets. NULL for CLI runs and runs with no Kappa
    # session, and for runs started before this column existed.
    kappa_dataset_id = Column(Integer, nullable=True)

    # Остановка оператором: на каком этапе прервали и кто нажал кнопку.
    stopped_at_stage = Column(Integer, nullable=True)
    stopped_by = Column(String, nullable=True)

    # Если этот запуск — requeue (повторная обработка после ручной правки),
    # здесь лежит run_id исходного запуска. NULL для обычных запусков.
    parent_run_id = Column(String, nullable=True)

    # Deferred Kappa delivery. `kappa_upload_status` is NULL for runs that
    # never intended to upload (CLI, no Kappa session) — the worker ignores
    # those entirely. `kappa_upload_detail` is a JSON blob (see
    # backend/kappa_delivery.py). `kappa_user_id` is the Kappa account that
    # started the run: session ids rotate on re-login, user ids do not, so
    # this is what finds a live token days later.
    kappa_upload_status = Column(String, nullable=True)
    kappa_upload_next_attempt = Column(DateTime, nullable=True)
    kappa_upload_detail = Column(Text, nullable=True)
    kappa_user_id = Column(Integer, nullable=True)

    # Sessions this run rebuilt because the doctor corrected their modality
    # set. JSON list of "sub-NNN_ses-NNN". Their results in Kappa were
    # computed from a set now known to be wrong, so they supersede rather
    # than duplicate — see kappa_uploader.
    reprocessed_sessions = Column(Text, nullable=True)


class StageExecution(Base):
    """Модель выполнения отдельного этапа"""
    __tablename__ = "stage_executions"
    
    id = Column(Integer, primary_key=True, autoincrement=True)
    run_id = Column(String, nullable=False, index=True)
    stage_number = Column(Integer, nullable=False)
    stage_name = Column(String, nullable=False)
    status = Column(String, nullable=False, default="pending")
    progress = Column(Float, default=0.0)
    
    started_at = Column(DateTime, nullable=True)
    completed_at = Column(DateTime, nullable=True)
    
    error_message = Column(Text, nullable=True)


