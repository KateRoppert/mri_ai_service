def get_db() -> Session:
    """Получить сессию БД"""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


def create_pipeline_run(
    db: Session,
    input_path: str,
    output_path: str,
    lesion_type: str = 'glioblastoma',
    parent_run_id: Optional[str] = None,
    kappa_dataset_id: Optional[int] = None,
    run_id: Optional[str] = None,
    kappa_upload_status: Optional[str] = None,
    kappa_user_id: Optional[int] = None,
    reprocessed_sessions: Optional[str] = None,
) -> PipelineRun:
    """Создать новый запуск pipeline.

    run_id may be pre-generated by the caller — needed when the BIDS
    numbering scope has to be decided (backend/numbering.py) before the row
    exists, since a pending scope (Kappa unreachable at start) is keyed by
    this exact run_id and must match what get_pipeline_run() later returns.

    kappa_upload_status is the delivery intent, recorded at birth: 'pending'
    when the caller supplied a live Kappa session, None (the default) for
    CLI/orchestrator runs that never intended to upload. A None status keeps
    the run out of the deferred-delivery worker's queue permanently.
    """
    run_id = run_id or str(uuid.uuid4())

    run = PipelineRun(
        run_id=run_id,
        input_path=input_path,
        output_path=output_path,
        status="pending",
        created_at=datetime.now(timezone.utc),
        lesion_type=lesion_type,
        parent_run_id=parent_run_id,
        kappa_dataset_id=kappa_dataset_id,
        kappa_upload_status=kappa_upload_status,
        kappa_user_id=kappa_user_id,
        reprocessed_sessions=reprocessed_sessions,
    )
    
    db.add(run)
    db.commit()
    db.refresh(run)
    
    # Создаём записи для всех этапов
    stage_names = settings.stage_names_ru
    for stage_num in range(1, 8):
        stage = StageExecution(
            run_id=run_id,
            stage_number=stage_num,
            stage_name=stage_names[stage_num],
            status="pending"
        )
        db.add(stage)
    
    db.commit()
    
    return run


def get_pipeline_run(db: Session, run_id: str) -> Optional[PipelineRun]:
    """Получить информацию о запуске по ID"""
    return db.query(PipelineRun).filter(PipelineRun.run_id == run_id).first()


def get_active_run_by_output_path(db: Session, output_path: str) -> Optional[PipelineRun]:
    """Найти запуск в статусе pending/running на заданном output_path.

    Несколько разных run_id (например, run и его собственный requeue-потомок)
    могут указывать на один и тот же output_path. Перед тем как поставить в
    очередь ещё один запуск на этот путь, нужно убедиться, что там прямо
    сейчас не работает другой процесс — иначе два orchestrator-процесса
    начнут конкурентно писать в один bids_organized/dataset_mapping.json.
    """
    return db.query(PipelineRun).filter(
        PipelineRun.output_path == output_path,
        PipelineRun.status.in_(["running", "pending"])
    ).first()


def update_pipeline_run(
    db: Session,
    run_id: str,
    **kwargs
) -> Optional[PipelineRun]:
    """Обновить информацию о запуске"""
    run = get_pipeline_run(db, run_id)
    if not run:
        return None
    
    for key, value in kwargs.items():
        if hasattr(run, key):
            setattr(run, key, value)
    
    db.commit()
    db.refresh(run)
    return run


def update_pipeline_run_if_active(
    db: Session,
    run_id: str,
    **kwargs
) -> Optional[PipelineRun]:
    """
    Apply updates only while the run is still pending or running.

    Atomic at the SQL level so a late completed/failed write cannot
    overwrite a stop that already committed on another Session.
    Returns None when the row was already terminal (or missing).
    """
    allowed = {k: v for k, v in kwargs.items() if hasattr(PipelineRun, k)}
    if not allowed:
        return get_pipeline_run(db, run_id)

    rows = (
        db.query(PipelineRun)
        .filter(
            PipelineRun.run_id == run_id,
            PipelineRun.status.in_(["pending", "running"]),
        )
        .update(allowed, synchronize_session="fetch")
    )
    db.commit()
    if rows == 0:
        return None
    return get_pipeline_run(db, run_id)


def reconcile_orphaned_runs(db: Session) -> int:
    """Mark runs stuck in a non-terminal state as failed at startup.

    A pipeline run executes as a subprocess of the backend, so it cannot outlive
    a backend/container restart. Any run still marked 'running' or 'pending' when
    the backend boots is therefore orphaned — its process died. Left untouched,
    these 'running' rows keep the frontend history auto-refresh polling forever
    and mislead the user into thinking work is still in progress.

    Returns the number of runs reconciled.
    """
    orphaned = db.query(PipelineRun).filter(
        PipelineRun.status.in_(["running", "pending"])
    ).all()
    if not orphaned:
        return 0

    now = datetime.utcnow()
    for run in orphaned:
        run.status = "failed"
        run.completed_at = now
        run.error_message = (
            run.error_message
            or "Прогон прерван перезапуском сервиса (orphaned at startup)"
        )
        # A failed run produced nothing to upload. Left 'pending' it would
        # haunt the summary banner forever, because the delivery worker only
        # ever looks at completed runs.
        run.kappa_upload_status = None
        run.kappa_upload_next_attempt = None
    db.commit()
    return len(orphaned)


def get_stage_executions(db: Session, run_id: str) -> List[StageExecution]:
    """Получить все этапы для запуска"""
    return db.query(StageExecution).filter(
        StageExecution.run_id == run_id
    ).order_by(StageExecution.stage_number).all()


def update_stage_execution(
    db: Session,
    run_id: str,
    stage_number: int,
    **kwargs
) -> Optional[StageExecution]:
    """Обновить информацию об этапе"""
    stage = db.query(StageExecution).filter(
        StageExecution.run_id == run_id,
        StageExecution.stage_number == stage_number
    ).first()
    
    if not stage:
        return None
    
    for key, value in kwargs.items():
        if hasattr(stage, key):
            setattr(stage, key, value)
    
    db.commit()
    db.refresh(stage)
    return stage


def get_pipeline_history(
    db: Session,
    limit: int = 50,
    offset: int = 0
) -> tuple[List[PipelineRun], int]:
    """Получить историю запусков с пагинацией"""
    query = db.query(PipelineRun).order_by(PipelineRun.created_at.desc())
    
    total = query.count()
    runs = query.limit(limit).offset(offset).all()
    
    return runs, total


